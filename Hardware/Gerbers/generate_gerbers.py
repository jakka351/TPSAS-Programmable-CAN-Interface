# 4.  NPTH Excellon drill file  (TP-CAN-2I-NPTH.drl)
# ---------------------------------------------------------------------------
def build_npth_drill() -> str:
    """Excellon NPTH drill file for 4x M3 holes Ø3.2 mm."""
    # Excellon metric trailing-zero format: coordinates in mm * 1000
    # METRIC,TZ means Trailing Zeros suppressed → leading zeros kept
    # e.g. X4000Y4000 = (4.000, 4.000) mm
    def ec(v: float) -> str:
        """Excellon coordinate: mm × 1000, no decimal point."""
        return str(round(v * 1000))

    out = [
        "M48",
        "METRIC,TZ",
        "; TP-CAN-2I NPTH drill file",
        "; 4 x M3 mounting holes  Diameter 3.200 mm",
        f"T1C{MH_D:.3f}",
        "%",          # end of header
        "G05",        # drill mode
        "T1",
    ]
    for (x, y) in MH:
        out.append(f"X{ec(x)}Y{ec(y)}")
    out.append("M30")
    return "\n".join(out) + "\n"


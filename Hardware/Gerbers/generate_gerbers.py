#!/usr/bin/env python3
"""
TP-CAN-2I  Mechanical / Fab Gerber + Excellon generator
=========================================================
Produces a manufacturer-ready (but copper-incomplete) Gerber set that
honestly represents what exists in the KiCad MECHANICAL STARTING BOARD:

  * Board outline (70 x 50 mm, R3 rounded corners)          -> Edge.Cuts
  * Two isolation milling slots (under U9/U10)               -> Edge.Cuts
  * 4x M3 NPTH mounting holes Ø3.2 mm                       -> NPTH.drl
  * Silkscreen: branding, isolation-barrier line, mtg rings  -> F.Silkscreen
  * Copper / mask layers: VALID RS-274X headers, NO features -> placeholder
  * Gerber Job JSON                                           -> .gbrjob
  * Layer map + fab README

COPPER AND SOLDERMASK LAYERS ARE INTENTIONAL PLACEHOLDERS.
They carry only a valid RS-274X header and M02* end-of-file marker.
Complete them by running  File > Fabrication Outputs > Gerbers  inside
KiCad after schematic capture, footprint assignment, placement, and routing.

RS-274X format used:  %FSLAX46Y46*%  (metric, 4 integer / 6 decimal digits)
Coordinate unit: mm × 1 000 000  as a signed integer.
"""

import math
import zipfile
import json
import os
import re
from pathlib import Path

# ---------------------------------------------------------------------------
# Paths
# ---------------------------------------------------------------------------
SCRIPT_DIR = Path(__file__).parent.resolve()
OUT = SCRIPT_DIR          # output next to this script inside Hardware/Gerbers/

# ---------------------------------------------------------------------------
# Board geometry (from generate_board.py)
# ---------------------------------------------------------------------------
W, H  = 70.0, 50.0   # board width / height  (mm)
R     = 3.0           # corner radius
K     = R * (1 - math.sqrt(0.5))   # = R*(1-1/√2) ≈ 0.8787 mm

MH = [(4.0, 4.0), (66.0, 4.0), (4.0, 46.0), (66.0, 46.0)]  # NPTH centres
MH_D = 3.2           # NPTH drill diameter (mm)
MH_SILK_R = 3.0      # silk ring outer diameter (mm) -- ring drawn at this radius

# Isolation milling slots  [x0,y0, x1,y1]
SLOTS = [
    (57.3,  8.5, 58.7, 15.5),
    (57.3, 29.5, 58.7, 36.5),
]

# ---------------------------------------------------------------------------
# RS-274X helpers
# ---------------------------------------------------------------------------
SCALE = 1_000_000   # mm → 4.6 integer

def c(v: float) -> int:
    """Convert mm to RS-274X 4.6 integer coordinate."""
    return round(v * SCALE)

def coord(x: float, y: float) -> str:
    """Format X/Y coordinate pair."""
    return f"X{c(x)}Y{c(y)}"

def gerber_header(file_function: str, polarity: str = "Positive") -> list[str]:
    """Return standard RS-274X preamble lines (as list, no newlines yet)."""
    return [
        "%FSLAX46Y46*%",
        "%MOMM*%",
        f"%TF.FileFunction,{file_function}*%",
        f"%TF.FilePolarity,{polarity}*%",
        "%TF.SameCoordinates,Original*%",
        "G04 --- Generated by TP-CAN-2I generate_gerbers.py ---*",
    ]

def gerber_footer() -> list[str]:
    return ["M02*"]

def apt(code: int, shape: str, params: str) -> str:
    """Aperture definition line, e.g. apt(10,'C','0.150')."""
    return f"%ADD{code}{shape},{params}*%"

# ---------------------------------------------------------------------------
# 1. Edge Cuts  (TP-CAN-2I-Edge_Cuts.gm1)
# ---------------------------------------------------------------------------
def build_edge_cuts() -> str:
    lines = gerber_header("Profile,NP")
    # Apertures: outline (0.12 mm) + slot outline (0.12 mm) — same width
    lines += [
        apt(10, "C", "0.120"),  # outline / slot line width
        "G04 Select outline aperture*",
        "D10*",
        "G04 --- Board outline: straight edges + G03 arcs for rounded corners ---*",
        "G75*",   # multi-quadrant arc mode (required before G02/G03)
    ]

    # Helper: draw a line segment
    def line(x0, y0, x1, y1):
        return [
            f"{coord(x0, y0)}D02*",   # move to start
            f"{coord(x1, y1)}D01*",   # draw
        ]

    # Helper: draw a G03 (CCW) arc
    # start→end with centre offset I/J (from current position = start)
    def arc_ccw(sx, sy, ex, ey, cx, cy):
        i = round((cx - sx) * SCALE)
        j = round((cy - sy) * SCALE)
        return [
            f"{coord(sx, sy)}D02*",
            f"G03{coord(ex, ey)}I{i}J{j}D01*",
        ]

    # ---- Four straight edges (KiCad coordinate system: Y increases downward) ----
    # Top edge:  (R,0) → (W-R, 0)
    lines += line(R, 0, W - R, 0)
    # Top-right arc: (W-R,0) → (W,R)  centre=(W,0)
    lines += arc_ccw(W - R, 0, W, R, W, 0)
    # Right edge: (W,R) → (W, H-R)
    lines += line(W, R, W, H - R)
    # Bottom-right arc: (W,H-R) → (W-R,H)  centre=(W,H)
    lines += arc_ccw(W, H - R, W - R, H, W, H)
    # Bottom edge: (W-R,H) → (R,H)
    lines += line(W - R, H, R, H)
    # Bottom-left arc: (R,H) → (0,H-R)  centre=(0,H)
    lines += arc_ccw(R, H, 0, H - R, 0, H)
    # Left edge: (0,H-R) → (0,R)
    lines += line(0, H - R, 0, R)
    # Top-left arc: (0,R) → (R,0)  centre=(0,0)
    lines += arc_ccw(0, R, R, 0, 0, 0)

    # ---- Isolation milling slots (rectangular outlines on Edge.Cuts) ----
    lines += ["G04 --- Isolation milling slots ---*"]
    for (x0, y0, x1, y1) in SLOTS:
        lines += line(x0, y0, x1, y0)   # top
        lines += line(x1, y0, x1, y1)   # right
        lines += line(x1, y1, x0, y1)   # bottom
        lines += line(x0, y1, x0, y0)   # left

    # ---- NPTH hole circles on Edge.Cuts (Ø3.2 mm) ----
    lines += ["G04 --- NPTH circles on Edge.Cuts (Ø3.2 mm) ---*",
              apt(11, "C", "0.120"),
              "D11*"]
    r_npth = MH_D / 2.0   # 1.6 mm
    for (cx, cy) in MH:
        # Draw circle as 4 quadrant arcs (G03 CCW full circle in 4 steps)
        # Start at right: (cx+r, cy)
        sx, sy = cx + r_npth, cy
        # Quarter 1: right → bottom  (cx+r,cy)→(cx,cy+r)  centre at (cx,cy)
        lines += [f"{coord(sx, sy)}D02*"]
        i0 = round((cx - sx)  * SCALE)
        j0 = round((cy - sy)  * SCALE)
        lines += [f"G03{coord(cx, cy + r_npth)}I{i0}J{j0}D01*"]
        i1 = round((cx - cx)  * SCALE)
        j1 = round((cy - (cy + r_npth)) * SCALE)
        lines += [f"G03{coord(cx - r_npth, cy)}I{i1}J{j1}D01*"]
        i2 = round((cx - (cx - r_npth)) * SCALE)
        j2 = round((cy - cy) * SCALE)
        lines += [f"G03{coord(cx, cy - r_npth)}I{i2}J{j2}D01*"]
        i3 = round((cx - cx) * SCALE)
        j3 = round((cy - (cy - r_npth)) * SCALE)
        lines += [f"G03{coord(sx, sy)}I{i3}J{j3}D01*"]

    lines += gerber_footer()
    return "\n".join(lines) + "\n"

# ---------------------------------------------------------------------------
# 2. Front Silkscreen  (TP-CAN-2I-F_Silkscreen.gto)
# ---------------------------------------------------------------------------
def build_f_silkscreen() -> str:
    lines = gerber_header("Legend,Top")
    lines += [
        "G04 --- Aperture definitions ---*",
        apt(10, "C", "0.150"),   # isolation barrier line  (0.2 mm → 0.15 min)
        apt(11, "C", "0.150"),   # mounting-hole silk rings
        apt(12, "C", "0.150"),   # general silk lines
        "G75*",
    ]

    # ---- Isolation-barrier vertical line: x=54, y=2..48 ----
    lines += [
        "G04 --- Galvanic isolation barrier line at x=54 mm ---*",
        "D10*",
        f"{coord(54.0, 2.0)}D02*",
        f"{coord(54.0, 48.0)}D01*",
    ]

    # ---- Channel-split horizontal line: x=54..70, y=24 ----
    lines += [
        "G04 --- Channel split line y=24 mm ---*",
        f"{coord(54.0, 24.0)}D02*",
        f"{coord(70.0, 24.0)}D01*",
    ]

    # ---- Mounting-hole silk rings  Ø3.0 mm circle ----
    lines += [
        "G04 --- Mounting hole silk rings (Ø3.0 mm) ---*",
        "D11*",
    ]
    r_silk = MH_SILK_R / 2.0  # 1.5 mm radius
    for (cx, cy) in MH:
        sx = cx + r_silk
        sy = cy
        lines += [f"{coord(sx, sy)}D02*"]
        i0 = round((cx - sx) * SCALE)
        j0 = 0
        lines += [f"G03{coord(cx, cy + r_silk)}I{i0}J{j0}D01*"]
        i1 = 0
        j1 = round((cy - (cy + r_silk)) * SCALE)
        lines += [f"G03{coord(cx - r_silk, cy)}I{i1}J{j1}D01*"]
        i2 = round((cx - (cx - r_silk)) * SCALE)
        j2 = 0
        lines += [f"G03{coord(cx, cy - r_silk)}I{i2}J{j2}D01*"]
        i3 = 0
        j3 = round((cy - (cy - r_silk)) * SCALE)
        lines += [f"G03{coord(sx, sy)}I{i3}J{j3}D01*"]

    # ---- Text annotations as %TF comment blocks (silkscreen text) ----
    # Full glyph stroking is omitted (no font data in this generator).
    # Instead, text content is declared via G04 comments and %TF attributes so
    # that the CAM operator and FAB_README.md carry the branding faithfully.
    # Physical text placement in KiCad will generate the real silkscreen glyphs
    # when the board is exported after routing.
    lines += [
        "G04 --- Silkscreen text elements (reference: rendered in KiCad export) ---*",
        "G04 TEXT @ (35.0, 49.3): TESTER PRESENT  TP-CAN-2I  Rev A*",
        "G04 TEXT @ (54.0, 24.0, rot90): <<  GALVANIC  ISOLATION  BARRIER  >>*",
        "G04 TEXT @ (24.0,  4.0): ANTENNA KEEP-OUT (no copper) ->*",
        "%TF.CreationDate,2026-06-01*%",
    ]

    lines += gerber_footer()
    return "\n".join(lines) + "\n"


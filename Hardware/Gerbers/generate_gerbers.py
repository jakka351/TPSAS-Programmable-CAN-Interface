# Validation helper
# ---------------------------------------------------------------------------
def validate_gerber(path: Path, tag: str):
    text = path.read_text(encoding="utf-8")
    errors = []
    if not text.startswith("%FSLAX46Y46*%"):
        errors.append("does not start with %FSLAX46Y46*%")
    if "%MOMM*%" not in text:
        errors.append("missing %MOMM*%")
    if not text.rstrip().endswith("M02*"):
        errors.append("does not end with M02*")
    # Check that every aperture used (Dnn* where nn>=10) is defined before use
    defined = set()
    for m in re.finditer(r'%ADD(\d+)', text):
        defined.add(int(m.group(1)))
    # Find all Dnn* draws/selects (not D01/D02/D03)
    used = set()
    for m in re.finditer(r'D(\d+)\*', text):
        code = int(m.group(1))
        if code >= 10:
            used.add(code)
    undefined = used - defined
    if undefined:
        errors.append(f"apertures used but not defined: {undefined}")
    if errors:
        print(f"  VALIDATION FAIL [{tag}]: {'; '.join(errors)}")
        return False
    print(f"  OK  {tag}")
    return True

def validate_excellon(path: Path, tag: str):
    text = path.read_text(encoding="utf-8")
    errors = []
    if not text.startswith("M48"):
        errors.append("does not start with M48")
    if "M30" not in text:
        errors.append("missing M30 end-of-file")
    if "T1C" not in text:
        errors.append("missing tool definition T1C")
    if errors:
        print(f"  VALIDATION FAIL [{tag}]: {'; '.join(errors)}")
        return False
    print(f"  OK  {tag}")
    return True


    files["FAB_README.md"]               = build_fab_readme()

    # Write all files
    for fname, content in files.items():
        fpath = OUT / fname
        fpath.write_text(content, encoding="utf-8")
        print(f"  wrote {fname}  ({len(content)} bytes)")

    # Validate Gerbers
    print("\nValidating Gerber files...")
    all_ok = True
    gerber_exts = {".gm1", ".gto", ".gtl", ".g2", ".g3", ".gbl", ".gts", ".gbs"}
    for fname in files:
        fpath = OUT / fname
        ext = Path(fname).suffix.lower()
        if ext in gerber_exts:
            all_ok &= validate_gerber(fpath, fname)
        elif ext == ".drl":
            all_ok &= validate_excellon(fpath, fname)

    # Zip
    zip_path = OUT / "TP-CAN-2I_Gerbers.zip"
    print(f"\nCreating {zip_path.name} ...")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        for fname in files:
            zf.write(OUT / fname, arcname=fname)
    print(f"  zip contains {len(files)} files, size={zip_path.stat().st_size} bytes")

    print("\n--- Summary ---")
    print(f"Output: {OUT}")
    print(f"Validation {'PASSED' if all_ok else 'FAILED (see above)'}")
    print("CAVEAT: Copper (F_Cu, In1_Cu, In2_Cu, B_Cu) and soldermask (F_Mask, B_Mask)")
    print("layers are PLACEHOLDER RS-274X files with no features — complete them via")
    print("KiCad after schematic capture, footprint placement, and full routing.")
    return 0 if all_ok else 1


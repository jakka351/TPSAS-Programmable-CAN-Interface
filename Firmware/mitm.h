// ----------------------------------------------------------------------------------------------------
//  mitm.h  -  CAN1 <-> CAN2 man-in-the-middle bridge. Reads each channel, applies a per-frame rule
//             hook honouring the config mitm_mode (0 passthru / 1 filter / 2 rewrite / 3 block), and
//             forwards to the opposite channel. Frames addressed to the DPP request ID (0x7FE) on the
//             active programming bus are skipped here (consumed by ISO-TP). Activity LEDs blink on
//             traffic. Kept intentionally simple but real.
// ----------------------------------------------------------------------------------------------------

#ifndef TP_MITM_H
#define TP_MITM_H

#include <Arduino.h>
#include "mcp2518fd.h"
#include "transports.h"
#include "config.h"

// Outcome of the per-frame rule hook.
enum MitmAction {
  MITM_PASS,      // forward unchanged
  MITM_REWRITE,   // forward the (possibly) modified frame
  MITM_DROP       // do not forward
};

class Mitm {
public:
  Mitm();

  // can1 = vehicle/upstream (U7), can2 = ECU/downstream (U8). transports is used so we can hand any
  // frame matching the DPP request ID to ISO-TP instead of bridging it.
  void begin(MCP2518FD *can1, MCP2518FD *can2, Transports *tr);

  // Set the live MITM mode (from the config blob; updated when config changes via DID 0x0100).
  void setMode(uint8_t mode) { _mode = mode; }

  // Tell the bridge which bus currently carries the programming traffic (so it can route those frames
  // to ISO-TP rather than forwarding them). PROG_BUS_CAN1 or PROG_BUS_CAN2.
  void setProgBus(uint8_t bus) { _progBus = bus; }

  // Pump both directions once. Non-blocking; call every loop().
  void service();

private:
  MCP2518FD *_can1;
  MCP2518FD *_can2;
  Transports *_tr;
  uint8_t    _mode;
  uint8_t    _progBus;

  // LED activity one-shot timers (ms of last traffic).
  uint32_t _led1Until;
  uint32_t _led2Until;

  // The per-frame rule hook. `fromCan1` indicates direction. May edit `f` in place when rewriting.
  MitmAction ruleHook(CanFrame &f, bool fromCan1);

  // Forward one direction: read source, apply hook, write destination. Returns true if a frame moved.
  bool bridgeOne(MCP2518FD *src, MCP2518FD *dst, bool fromCan1, uint8_t srcBusId, uint8_t ledPin, uint32_t &ledUntil);
};

#endif // TP_MITM_H
